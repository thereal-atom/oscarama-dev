/** a seeded "dissolve" strip: each row down fills in more cells — a dither gradient at giant scale */
export function dissolve(seed: number, cols: number, rows: number): string[] {
  let s = seed * 9301 + 49297;
  const rnd = () => ((s = (s * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff);
  return Array.from({ length: rows }, (_, y) => Array.from({ length: cols }, () => (rnd() < (y + 1) / (rows + 1) ? "#" : ".")).join(""));
}
