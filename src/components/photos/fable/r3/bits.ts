/** rows of a word set in the bitmap alphabet (1 empty column between glyphs, 3 between words) */
export function glyphRows(text: string): string[] {
  const gs = [...text.toUpperCase()].map((ch) => G[ch] ?? G[" "]);
  return Array.from({ length: 7 }, (_, y) => gs.map((g) => g[y]).join("."));
}

